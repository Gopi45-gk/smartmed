# ─── Script Detection & Language Helpers ─────────────────────────────────────

def detect_language(text: str, fallback: str = "en") -> str:
    """Detect language based on Unicode character blocks or fallback."""
    if not text:
        return fallback

    # Tamil: U+0B80 to U+0BFF
    if re.search(r"[\u0B80-\u0BFF]", text):
        return "ta"
    # Hindi / Devanagari: U+0900 to U+097F
    if re.search(r"[\u0900-\u097F]", text):
        return "hi"
    # Telugu: U+0C00 to U+0C7F
    if re.search(r"[\u0C00-\u0C7F]", text):
        return "te"
    # Malayalam: U+0D00 to U+0D7F
    if re.search(r"[\u0D00-\u0D7F]", text):
        return "ml"
    # Kannada: U+0C80 to U+0CFF
    if re.search(r"[\u0C80-\u0CFF]", text):
        return "kn"
    # Urdu / Arabic: U+0600 to U+06FF
    if re.search(r"[\u0600-\u06FF]", text):
        return "ur"

    # Normalize fallback code
    code = (fallback or "en").lower().split("-")[0].strip()
    return code if code in ["en", "ta", "hi", "te", "ml", "kn", "ur"] else "en"


